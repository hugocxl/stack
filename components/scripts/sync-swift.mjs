// Bring the design-system tokens and fonts into the Swift sources, from the published
// @hugocxl/design-system package the workspace installs (never the workspace copy).
//
//   Sources/Components/Tokens.swift        colors, spacing, radii and sizes
//   Sources/Components/Resources/Fonts/    Geist Sans and Geist Mono
//
// Usage: node scripts/sync-swift.mjs [--check]
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const check = process.argv.includes("--check");
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(join(root, "package.json"));
const designSystem = dirname(require.resolve("@hugocxl/design-system/package.json"));
const tokens = JSON.parse(readFileSync(join(designSystem, "dist/tokens.json"), "utf8"));
const { version } = JSON.parse(readFileSync(join(designSystem, "package.json"), "utf8"));

const camel = (name) => name.replace(/-(\w)/g, (_, c) => c.toUpperCase());
const rem = (value) => {
  const match = /^(-?\d*\.?\d+)(rem|px)$/.exec(value);
  if (!match) throw new Error(`Cannot convert ${value} to points`);
  return Number(match[1]) * (match[2] === "rem" ? 16 : 1);
};
const hex = (value) => {
  const match = /^#([0-9a-f]{6})([0-9a-f]{2})?$/i.exec(value);
  if (!match) throw new Error(`Unexpected color ${value}`);
  return `0x${match[1].toUpperCase()}${(match[2] ?? "ff").toUpperCase()}`;
};

const roles = Object.keys(tokens.color.light);
const colorLines = roles.map(
  (role) => `    public static let ${camel(role)} = DSColorToken(light: ${hex(tokens.color.light[role])}, dark: ${hex(tokens.color.dark[role])})`,
);
const spaceLines = Object.entries(tokens.space).map(([step, value]) => `    public static let s${step}: CGFloat = ${rem(value)}`);
const radiusLines = Object.entries(tokens.radius).map(([name, value]) => `    public static let ${camel(name)}: CGFloat = ${rem(value)}`);

const swift = `// Generated by components/scripts/sync-swift.mjs from @hugocxl/design-system ${version}. Do not edit.
import CoreGraphics

/// The light and dark values of one color role, as 0xRRGGBBAA.
public struct DSColorToken: Sendable, Hashable {
    public let light: UInt32
    public let dark: UInt32
}

/// Every color role of the design system.
public enum DSColorTokens {
${colorLines.join("\n")}
}

/// The ten spacing steps, in points (1rem = 16pt).
public enum DSSpace {
${spaceLines.join("\n")}
}

/// Corner radii, in points.
public enum DSRadius {
${radiusLines.join("\n")}
}

/// Layout sizes, in points.
public enum DSLayout {
    /// The smallest interactive target.
    public static let target: CGFloat = ${rem(tokens.layout.target)}
    /// The reading column: 30em of the 17pt reading size, about 65 characters.
    public static let measure: CGFloat = ${30 * 17}
}
`;

const outputs = [[join(root, "Sources/Components/Tokens.swift"), swift]];
const fontsOut = join(root, "Sources/Components/Resources/Fonts");
const fonts = ["Geist-Variable.woff2", "GeistMono-Variable.woff2", "Geist-LICENSE.txt"];

let stale = [];
for (const [path, content] of outputs) {
  const current = existsSync(path) ? readFileSync(path, "utf8") : null;
  if (current === content) continue;
  if (check) stale.push(path);
  else writeFileSync(path, content);
}
mkdirSync(fontsOut, { recursive: true });
for (const font of fonts) {
  const source = join(designSystem, "system/fonts", font);
  const target = join(fontsOut, font);
  if (existsSync(target) && readFileSync(target).equals(readFileSync(source))) continue;
  if (check) stale.push(target);
  else copyFileSync(source, target);
}
if (stale.length) {
  console.error(`Out of date with @hugocxl/design-system ${version}; run pnpm run sync:\n  ${stale.join("\n  ")}`);
  process.exit(1);
}
console.log(check ? `Swift tokens and fonts match @hugocxl/design-system ${version}.` : `Synced Swift tokens and fonts from @hugocxl/design-system ${version}.`);
