// Generates the package's integration files from the tokens in system/p9.css, so they can never
// drift from the system: plain CSS variables, SCSS, JSON/JS, and Tailwind v4 and v3 setups.
// Usage: node scripts/build-exports.mjs [--check]
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const css = readFileSync(new URL('system/p9.css', root), 'utf8');

function block(selector) {
  const start = css.indexOf(`${selector} {`);
  if (start < 0) throw new Error(`system/p9.css has no ${selector} block`);
  const body = css.slice(css.indexOf('{', start) + 1, css.indexOf('\n}', start));
  return Object.fromEntries([...body.matchAll(/^\s*--p9-([a-z0-9-]+):\s*([^;]+);/gm)].map(m => [m[1], m[2].trim()]));
}

const light = block(':root');
const dark = block(':root[data-theme=dark]');
const colors = Object.keys(light).filter(name => /^#/.test(light[name]));
const pick = prefix => Object.keys(light).filter(name => name.startsWith(prefix));
const v = name => `var(--p9-${name})`;

const tokens = {
  color: { light: Object.fromEntries(colors.map(n => [n, light[n]])), dark: Object.fromEntries(colors.map(n => [n, dark[n] ?? light[n]])) },
  font: { sans: light.sans, mono: light.mono },
  size: Object.fromEntries(pick('size-').map(n => [n.slice(5), light[n]])),
  space: Object.fromEntries(pick('space-').map(n => [n.slice(6), light[n]])),
  radius: Object.fromEntries(pick('radius-').map(n => [n.slice(7), light[n]])),
  layout: { target: light.target, measure: light.measure, wide: light.wide },
  motion: { ease: light.ease },
};

const declarations = (vars, indent = '  ') => Object.entries(vars).map(([n, value]) => `${indent}--p9-${n}: ${value};`).join('\n');
const darkVars = Object.fromEntries(Object.entries(dark));
const header = '/* Generated by scripts/build-exports.mjs from system/p9.css. Do not edit. */\n';

const files = {};

// The Geist faces, pointing at the fonts that ship in system/fonts.
files['dist/fonts.css'] = header + [...css.matchAll(/@font-face \{[^}]*\}/g)].map(m => m[0].replace('url("fonts/', 'url("../system/fonts/')).join('\n') + '\n';

// Plain CSS: the tokens alone, for projects that bring their own components.
files['dist/tokens.css'] = header + `:root {
${declarations(light)}
  color-scheme: light;
}
:root[data-theme=dark] {
${declarations(darkVars)}
  color-scheme: dark;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme=light]) {
${declarations(darkVars, '    ')}
    color-scheme: dark;
  }
}
`;

// SCSS: one variable per token, pointing at the custom property so themes keep working.
// Load tokens.css once in the page for the values themselves.
files['dist/tokens.scss'] = '// Generated by scripts/build-exports.mjs from system/p9.css. Do not edit.\n' + Object.keys(light).map(n => `$p9-${n}: ${v(n)};`).join('\n') + '\n';

// JSON and JS: raw values for tooling, charts and native apps.
files['dist/tokens.json'] = JSON.stringify(tokens, null, 2) + '\n';
files['dist/tokens.js'] = header + `export const tokens = ${JSON.stringify(tokens, null, 2)};\nexport default tokens;\n`;
files['dist/tokens.d.ts'] = header + `export declare const tokens: ${JSON.stringify(tokens, null, 2).replace(/"([^"]+)": "[^"]*"/g, '"$1": string')};\nexport default tokens;\n`;

// Tailwind v4: @import "@hugocxl/design-system/tailwind.css" after tailwindcss.
const theme = [
  ...colors.map(n => `  --color-${n}: ${v(n)};`),
  `  --font-sans: ${v('sans')};`,
  `  --font-mono: ${v('mono')};`,
  ...pick('size-').map(n => `  --text-${n.slice(5)}: ${v(n)};`),
  ...pick('space-').map(n => `  --spacing-${n}: ${v(n)};`),
  ...pick('radius-').map(n => `  --radius-${n.slice(7)}: ${v(n)};`),
  `  --container-measure: ${v('measure')};`,
  `  --container-wide: ${v('wide')};`,
  `  --spacing-target: ${v('target')};`,
];
files['dist/tailwind.css'] = header + `@import "./fonts.css";
@import "./tokens.css";
@custom-variant dark (&:where([data-theme=dark], [data-theme=dark] *));

@theme inline {
${theme.join('\n')}
}
`;

// Tailwind v3: presets: [require("@hugocxl/design-system/tailwind-preset")], plus tokens.css in your CSS.
const preset = {
  darkMode: ['selector', '[data-theme="dark"]'],
  theme: {
    extend: {
      colors: Object.fromEntries(colors.map(n => [n, v(n)])),
      fontFamily: { sans: [v('sans')], mono: [v('mono')] },
      fontSize: Object.fromEntries(pick('size-').map(n => [n.slice(5), v(n)])),
      spacing: { ...Object.fromEntries(pick('space-').map(n => [n, v(n)])), target: v('target') },
      borderRadius: Object.fromEntries(pick('radius-').map(n => [n.slice(7), v(n)])),
      maxWidth: { measure: v('measure'), wide: v('wide') },
    },
  },
};
files['dist/tailwind-preset.cjs'] = header + `module.exports = ${JSON.stringify(preset, null, 2)};\n`;

const stale = [];
for (const [path, content] of Object.entries(files)) {
  const url = new URL(path, root);
  if (process.argv.includes('--check')) {
    if (!existsSync(url) || readFileSync(url, 'utf8') !== content) stale.push(path);
  } else {
    mkdirSync(new URL('dist/', root), { recursive: true });
    writeFileSync(url, content);
  }
}
if (stale.length) {
  console.error(`Out of date: ${stale.join(', ')}. Run npm run build.`);
  process.exit(1);
}
console.log(`${process.argv.includes('--check') ? 'Verified' : 'Wrote'} ${Object.keys(files).length} export files from ${Object.keys(light).length} tokens.`);
