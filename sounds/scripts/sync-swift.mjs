// Bring the sound catalog into the Swift sources, so the Sounds library synthesizes exactly the
// sounds the npm package does, from the same data.
//
//   sounds/Sources/Sounds/Catalog.swift    every sound, its layers and the haptic map
//
// Usage: node scripts/sync-swift.mjs [--check]   (after pnpm run build)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const check = process.argv.includes("--check");
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const { sounds, groups, feedback } = await import(pathToFileURL(join(root, "packages/sounds/dist/catalog.js")).href);
const { version } = JSON.parse(readFileSync(join(root, "packages/sounds/package.json"), "utf8"));

const camel = (name) => name.replace(/-(\w)/g, (_, c) => c.toUpperCase());
const num = (value) => (Number.isInteger(value) ? `${value}` : `${value}`);
const string = (value) => JSON.stringify(value);

const layer = (l) => {
  const at = num(l.at ?? 0);
  if (l.kind === "noise") {
    return `.noise(at: ${at}, filter: .${l.filter ?? "bandpass"}, frequency: ${num(l.freq)}, q: ${num(l.q ?? 1)}, level: ${num(l.level)}, decay: ${num(l.decay)})`;
  }
  return `.tone(at: ${at}, wave: .${l.wave ?? "sine"}, frequency: ${num(l.freq)}, to: ${num(l.to ?? l.freq)}, level: ${num(l.level)}, decay: ${num(l.decay)}, attack: ${num(l.attack ?? 0.001)})`;
};

const names = Object.keys(sounds);
const cases = names.map((name) => `    case ${camel(name)} = ${string(name)}`).join("\n");
const definitions = names
  .map((name) => {
    const sound = sounds[name];
    return `        case .${camel(name)}:\n            return DSSoundDefinition(group: .${sound.group}, description: ${string(sound.description ?? "")}, layers: [\n${sound.layers.map((l) => `                ${layer(l)},`).join("\n")}\n            ])`;
  })
  .join("\n");
const groupCases = Object.entries(groups).map(([key, title]) => `    case ${key}\n`).join("");
const groupTitles = Object.entries(groups).map(([key, title]) => `        case .${key}: return ${string(title)}`).join("\n");
const feedbackCases = Object.keys(feedback).map((kind) => `    case ${kind}`).join("\n");
const feedbackSounds = Object.entries(feedback).map(([kind, f]) => `        case .${kind}: return .${camel(f.sound)}`).join("\n");

const swift = `// Generated by sounds/scripts/sync-swift.mjs from @hugocxl/sounds ${version}. Do not edit.

/// Every interface sound of @hugocxl/sounds.
public enum DSSound: String, CaseIterable, Sendable {
${cases}

    /// The layers the sound is synthesized from.
    public var definition: DSSoundDefinition {
        switch self {
${definitions}
        }
    }
}

/// The family a sound belongs to.
public enum DSSoundGroup: String, CaseIterable, Sendable {
${groupCases.trimEnd()}

    public var title: String {
        switch self {
${groupTitles}
        }
    }
}

/// iOS-style haptic feedback, each mapped to the sound it makes.
public enum DSFeedback: String, CaseIterable, Sendable {
${feedbackCases}

    public var sound: DSSound {
        switch self {
${feedbackSounds}
        }
    }
}
`;

const target = join(root, "Sources/Sounds/Catalog.swift");
if (check) {
  if (readFileSync(target, "utf8") !== swift) {
    console.error("sounds/Sources/Sounds/Catalog.swift is out of date; run pnpm run sync:swift");
    process.exit(1);
  }
  console.log("Catalog.swift matches the catalog.");
} else {
  writeFileSync(target, swift);
  console.log(`Wrote Catalog.swift with ${names.length} sounds.`);
}
